import { writeFile, readFile, mkdir } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const base=process.env.TEST_URL||"http://127.0.0.1:4326";
if(!["localhost","127.0.0.1"].includes(new URL(base).hostname))throw Error("This audit targets the local feature preview.");
const xml=await(await fetch(`${base}/sitemap.xml`)).text();
const routes=[...xml.matchAll(/<loc>(.*?)<\/loc>/g)].map(m=>new URL(m[1]).pathname);
const report={base,routes:[],links:[],images:[],errors:[]};
const links=new Set(),images=new Set();
const decode=value=>value.replaceAll("&amp;","&").replaceAll("&#x27;","'").replaceAll("&quot;",'"');
for(const route of routes){
  const response=await fetch(base+route),html=await response.text();
  const markup=html.replace(/<script\b[^>]*>[\s\S]*?<\/script>/g,"");
  const h1=[...markup.matchAll(/<h1[\s>]/g)].length;
  const missingAlt=[...markup.matchAll(/<img\b[^>]*>/g)].filter(m=>! /\balt="[^"]*"/.test(m[0]));
  const aiLabel=/AI[- ]generated|AI[- ]assisted|made with AI|generated by (?:OpenAI|ChatGPT)/i.test(markup);
  const eyebrows=/class="[^"]*(?:\bkicker\b|eyebrow)[^"]*"/i.test(markup);
  const decorativeArrow=/<(?:a|button)\b[^>]*>[\s\S]*?[↗→][\s\S]*?<\/(?:a|button)>/.test(markup);
  report.routes.push({route,status:response.status,h1,missingAlt:missingAlt.length,aiLabel,eyebrows,decorativeArrow});
  if(response.status!==200||h1!==1||missingAlt.length||aiLabel||eyebrows||decorativeArrow)report.errors.push({route,reason:"Page structure or content check",h1,missingAlt:missingAlt.length,aiLabel,eyebrows,decorativeArrow});
  for(const [,href] of markup.matchAll(/<a\b[^>]*href="([^"]+)"/g)){
    const url=new URL(decode(href),base+route);
    if(url.origin===new URL(base).origin)links.add(url.pathname+url.search);
  }
  for(const [,src] of markup.matchAll(/<img\b[^>]*src="([^"]+)"/g))images.add(decode(src));
}
for(const href of links){
  const response=await fetch(new URL(href,base),{method:"HEAD"});
  report.links.push({href,status:response.status});
  if(!response.ok)report.errors.push({href,status:response.status,reason:"Broken internal link"});
}
const assetMetadata=[];
for(const src of images){
  const response=await fetch(new URL(src,base),{method:"HEAD"});
  report.images.push({src,status:response.status});
  if(!response.ok)report.errors.push({src,status:response.status,reason:"Broken image"});
  const url=new URL(src,base),asset=url.pathname==="/_next/image"?url.searchParams.get("url"):url.pathname;
  if(!asset?.startsWith("/")||asset.startsWith("/_next/"))continue;
  const filename=path.resolve("public",`.${asset}`);
  if(!filename.startsWith(path.resolve("public")+path.sep))continue;
  try{
    const bytes=await readFile(filename),meta=await sharp(bytes).metadata();
    const provenance=/c2pa|chatgpt|openai|gpt-image/i.test(bytes.toString("latin1"));
    assetMetadata.push({asset,bytes:bytes.length,exif:Boolean(meta.exif),xmp:Boolean(meta.xmp),iptc:Boolean(meta.iptc),provenance});
    if(provenance)report.errors.push({asset,reason:"Provenance text found in served image asset"});
  }catch(error){report.errors.push({asset,reason:`Asset inspection failed: ${error.message}`});}
}
report.assetMetadata=assetMetadata;
await mkdir(path.resolve("../../output/seo"),{recursive:true});
await writeFile(path.resolve("../../output/seo/public-site-audit.json"),JSON.stringify(report,null,2)+"\n");
console.log(JSON.stringify({pages:report.routes.length,internalLinks:report.links.length,imageUrls:report.images.length,inspectedAssets:assetMetadata.length,errors:report.errors},null,2));
if(report.errors.length)process.exitCode=1;
